-- Base de datos: Red social estudiantil pascualina
-- SGBD: PostgreSQL
-- Modelo físico elaborado a partir del modelo lógico del proyecto.
-- Grupo 3: Juan David Jovel - Angie Vanessa Rincón

BEGIN;

-- Datos principales de los estudiantes
CREATE TABLE estudiante (
    id_estudiante INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    correo_institucional VARCHAR(150) NOT NULL UNIQUE,
    programa_academico VARCHAR(120) NOT NULL,
    semestre SMALLINT NOT NULL,
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Cada estudiante puede tener un perfil
CREATE TABLE perfil (
    id_perfil INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante INTEGER NOT NULL UNIQUE,
    biografia TEXT,
    ciudad VARCHAR(100),
    foto_perfil TEXT,
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_estudiante) REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE
);

-- Habilidades que se pueden asociar a los estudiantes
CREATE TABLE habilidad (
    id_habilidad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion TEXT
);

CREATE TABLE estudiante_habilidad (
    id_estudiante INTEGER NOT NULL,
    id_habilidad INTEGER NOT NULL,
    nivel VARCHAR(30),
    fecha_aprendizaje DATE,
    PRIMARY KEY (id_estudiante, id_habilidad),
    FOREIGN KEY (id_estudiante) REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    FOREIGN KEY (id_habilidad) REFERENCES habilidad(id_habilidad)
        ON UPDATE CASCADE ON DELETE CASCADE
);

-- Intereses de la comunidad estudiantil
CREATE TABLE interes (
    id_interes INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion TEXT
);

CREATE TABLE estudiante_interes (
    id_estudiante INTEGER NOT NULL,
    id_interes INTEGER NOT NULL,
    fecha_agregado TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_estudiante, id_interes),
    FOREIGN KEY (id_estudiante) REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    FOREIGN KEY (id_interes) REFERENCES interes(id_interes)
        ON UPDATE CASCADE ON DELETE CASCADE
);

-- Relación de seguimiento entre dos estudiantes
CREATE TABLE seguir (
    id_seguidor INTEGER NOT NULL,
    id_seguido INTEGER NOT NULL,
    fecha_seguimiento TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_seguidor, id_seguido),
    FOREIGN KEY (id_seguidor) REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    FOREIGN KEY (id_seguido) REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CHECK (id_seguidor <> id_seguido)
);

-- Mensajes enviados entre estudiantes
CREATE TABLE mensaje (
    id_mensaje INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_emisor INTEGER NOT NULL,
    id_receptor INTEGER NOT NULL,
    texto TEXT NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'enviado',
    fecha_envio TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_emisor) REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    FOREIGN KEY (id_receptor) REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE
);

-- Grupos de estudiantes
CREATE TABLE grupo (
    id_grupo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    tema VARCHAR(100),
    descripcion TEXT
);

CREATE TABLE miembro_grupo (
    id_estudiante INTEGER NOT NULL,
    id_grupo INTEGER NOT NULL,
    rol VARCHAR(30) NOT NULL DEFAULT 'miembro',
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_estudiante, id_grupo),
    FOREIGN KEY (id_estudiante) REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    FOREIGN KEY (id_grupo) REFERENCES grupo(id_grupo)
        ON UPDATE CASCADE ON DELETE CASCADE
);

-- Eventos creados por un grupo
CREATE TABLE evento (
    id_evento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_grupo INTEGER NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    fecha TIMESTAMP NOT NULL,
    lugar VARCHAR(200),
    descripcion TEXT,
    FOREIGN KEY (id_grupo) REFERENCES grupo(id_grupo)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE asistente_evento (
    id_estudiante INTEGER NOT NULL,
    id_evento INTEGER NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'inscrito',
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_estudiante, id_evento),
    FOREIGN KEY (id_estudiante) REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    FOREIGN KEY (id_evento) REFERENCES evento(id_evento)
        ON UPDATE CASCADE ON DELETE CASCADE
);

-- Publicaciones, comentarios y reacciones
CREATE TABLE publicacion (
    id_publicacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante INTEGER NOT NULL,
    contenido TEXT NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo VARCHAR(30) NOT NULL DEFAULT 'texto',
    FOREIGN KEY (id_estudiante) REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE comentario (
    id_comentario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_publicacion INTEGER NOT NULL,
    id_estudiante INTEGER NOT NULL,
    contenido TEXT NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_publicacion) REFERENCES publicacion(id_publicacion)
        ON UPDATE CASCADE ON DELETE CASCADE,
    FOREIGN KEY (id_estudiante) REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE reaccion (
    id_reaccion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_publicacion INTEGER NOT NULL,
    id_estudiante INTEGER NOT NULL,
    tipo_reaccion VARCHAR(30) NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_publicacion) REFERENCES publicacion(id_publicacion)
        ON UPDATE CASCADE ON DELETE CASCADE,
    FOREIGN KEY (id_estudiante) REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE
);

COMMIT;
