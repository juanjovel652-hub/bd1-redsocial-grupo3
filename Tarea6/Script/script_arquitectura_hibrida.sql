-- 6. VISTAS ORIGINALES DEL PROYECTO, CONSERVADAS Y ADAPTADAS
CREATE OR REPLACE VIEW vista_perfiles_estudiantes AS
SELECT e.id_estudiante,e.nombre,e.apellido,e.correo_institucional,
       e.programa_academico,e.semestre,p.biografia,p.ciudad,
       (SELECT STRING_AGG(h.nombre,', ' ORDER BY h.nombre)
        FROM estudiante_habilidad eh JOIN habilidad h USING (id_habilidad)
        WHERE eh.id_estudiante=e.id_estudiante) AS habilidades,
       (SELECT STRING_AGG(i.nombre,', ' ORDER BY i.nombre)
        FROM estudiante_interes ei JOIN interes i USING (id_interes)
        WHERE ei.id_estudiante=e.id_estudiante) AS intereses
FROM estudiante e LEFT JOIN perfil p USING (id_estudiante);

CREATE OR REPLACE VIEW vista_popularidad_estudiantes AS
SELECT e.id_estudiante,e.nombre||' '||e.apellido AS nombre_estudiante,
       e.programa_academico,e.semestre,COUNT(s.id_seguidor) AS total_seguidores
FROM estudiante e LEFT JOIN seguir s ON e.id_estudiante=s.id_seguido
GROUP BY e.id_estudiante,e.nombre,e.apellido,e.programa_academico,e.semestre;

CREATE OR REPLACE VIEW vista_actividad_publicaciones AS
SELECT p.id_publicacion,p.contenido,p.tipo,p.fecha,
       e.nombre||' '||e.apellido AS autor,
       (SELECT COUNT(*) FROM comentario c WHERE c.id_publicacion=p.id_publicacion) AS total_comentarios,
       (SELECT COUNT(*) FROM reaccion r WHERE r.id_publicacion=p.id_publicacion) AS total_reacciones,
       (SELECT COUNT(*) FROM comentario c WHERE c.id_publicacion=p.id_publicacion)
       +(SELECT COUNT(*) FROM reaccion r WHERE r.id_publicacion=p.id_publicacion) AS total_interacciones
FROM publicacion p JOIN estudiante e USING (id_estudiante);

