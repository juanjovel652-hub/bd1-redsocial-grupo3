-- 7. CONSULTAS SOLICITADAS: RELACIONES + JSONB + IoT

-- C1. Adjuntos por autor y tipo, con peso acumulado.
SELECT e.nombre||' '||e.apellido AS autor,a->>'tipo' AS tipo_adjunto,
       COUNT(*) AS total_adjuntos,SUM((a->>'peso_kb')::numeric) AS peso_total_kb
FROM publicacion p JOIN estudiante e USING (id_estudiante)
CROSS JOIN LATERAL jsonb_array_elements(COALESCE(p.contenido->'adjuntos','[]'::jsonb)) a
GROUP BY autor,tipo_adjunto ORDER BY peso_total_kb DESC;

-- C2. Hashtags más utilizados.
SELECT h AS hashtag,COUNT(*) AS veces
FROM publicacion p
CROSS JOIN LATERAL jsonb_array_elements_text(COALESCE(p.contenido->'hashtags','[]'::jsonb)) h
GROUP BY h ORDER BY veces DESC,hashtag;

-- C3. Publicaciones que contienen el hashtag 'jsonb'.
SELECT id_publicacion,contenido->>'texto' AS texto
FROM publicacion WHERE contenido @> '{"hashtags":["jsonb"]}'::jsonb;

-- C4. Inscritos a eventos que tienen activadas las notificaciones.
SELECT ev.nombre,COUNT(*) AS inscritos_notificables
FROM evento ev JOIN asistente_evento ae USING (id_evento)
JOIN estudiante e USING (id_estudiante) JOIN perfil p USING (id_estudiante)
WHERE p.preferencias @> '{"notificaciones":{"eventos":true}}'::jsonb
GROUP BY ev.nombre;

-- C5. Ocupación promedio y máxima por aula y hora (10 de noviembre).
SELECT a.bloque,a.nombre AS aula,EXTRACT(HOUR FROM l.fecha_lectura) AS hora,
       ROUND(AVG((l.payload->>'personas')::numeric),1) AS promedio_personas,
       MAX((l.payload->>'personas')::integer) AS pico_personas
FROM lectura_iot l JOIN dispositivo_iot d USING (id_dispositivo)
JOIN aula a USING (id_aula)
WHERE d.tipo='ocupacion'
  AND l.fecha_lectura >= '2026-11-10' AND l.fecha_lectura < '2026-11-11'
GROUP BY a.bloque,a.nombre,EXTRACT(HOUR FROM l.fecha_lectura)
ORDER BY aula,hora;

-- C6. Alertas ambientales: temperatura mayor a 28 C o CO2 mayor a 1000 ppm.
SELECT a.nombre AS aula,COUNT(*) AS lecturas_criticas,
       ROUND(AVG((l.payload->>'temperatura')::numeric),1) AS temperatura_promedio
FROM lectura_iot l JOIN dispositivo_iot d USING (id_dispositivo)
JOIN aula a USING (id_aula)
WHERE d.tipo='ambiental'
  AND ((l.payload->>'temperatura')::numeric>28 OR (l.payload->>'co2')::integer>1000)
GROUP BY a.nombre HAVING COUNT(*)>10 ORDER BY lecturas_criticas DESC;

-- C7. Registros de asistencia generados mediante NFC.
SELECT e.nombre||' '||e.apellido AS estudiante,COUNT(*) AS registros_asistencia
FROM lectura_iot l JOIN dispositivo_iot d USING (id_dispositivo)
JOIN estudiante e ON e.id_estudiante=(l.payload->>'id_estudiante')::integer
WHERE d.tipo='asistencia'
GROUP BY estudiante ORDER BY registros_asistencia DESC;

-- C8. Actividad registrada por dispositivo y acción.
SELECT metadata->>'dispositivo' AS dispositivo,accion,COUNT(*) AS total
FROM log_actividad
WHERE fecha_log>='2026-11-01' AND fecha_log<'2026-11-08'
GROUP BY dispositivo,accion ORDER BY total DESC;

-- C9. Estudiantes con más publicaciones que el promedio.
SELECT e.nombre||' '||e.apellido AS estudiante,COUNT(p.id_publicacion) AS publicaciones
FROM estudiante e JOIN publicacion p USING (id_estudiante)
GROUP BY e.id_estudiante,e.nombre,e.apellido
HAVING COUNT(p.id_publicacion) >
 (SELECT AVG(cantidad) FROM
   (SELECT COUNT(*) AS cantidad FROM publicacion GROUP BY id_estudiante) x);

-- C10. Comprobación de las tres vistas conservadas.
SELECT * FROM vista_perfiles_estudiantes ORDER BY nombre;
SELECT * FROM vista_popularidad_estudiantes ORDER BY total_seguidores DESC;
SELECT * FROM vista_actividad_publicaciones ORDER BY total_interacciones DESC;

