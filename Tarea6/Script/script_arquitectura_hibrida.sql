BEGIN;

-- 1. MODELO RELACIONAL ORIGINAL (15 TABLAS)

CREATE TABLE estudiante (
    id_estudiante INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    correo_institucional VARCHAR(150) NOT NULL UNIQUE,
    programa_academico VARCHAR(120) NOT NULL,
    semestre SMALLINT NOT NULL CHECK (semestre > 0),
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE perfil (
    id_perfil INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante INTEGER NOT NULL UNIQUE REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    biografia TEXT,
    ciudad VARCHAR(100),
    foto_perfil TEXT,
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    preferencias JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT ck_perfil_preferencias_objeto CHECK (jsonb_typeof(preferencias) = 'object')
);

CREATE TABLE habilidad (
    id_habilidad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion TEXT
);

CREATE TABLE estudiante_habilidad (
    id_estudiante INTEGER NOT NULL REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    id_habilidad INTEGER NOT NULL REFERENCES habilidad(id_habilidad)
        ON UPDATE CASCADE ON DELETE CASCADE,
    nivel VARCHAR(30),
    fecha_aprendizaje DATE,
    PRIMARY KEY (id_estudiante, id_habilidad)
);

CREATE TABLE interes (
    id_interes INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion TEXT
);

CREATE TABLE estudiante_interes (
    id_estudiante INTEGER NOT NULL REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    id_interes INTEGER NOT NULL REFERENCES interes(id_interes)
        ON UPDATE CASCADE ON DELETE CASCADE,
    fecha_agregado TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_estudiante, id_interes)
);

CREATE TABLE seguir (
    id_seguidor INTEGER NOT NULL REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    id_seguido INTEGER NOT NULL REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    fecha_seguimiento TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_seguidor, id_seguido),
    CHECK (id_seguidor <> id_seguido)
);

CREATE TABLE mensaje (
    id_mensaje INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_emisor INTEGER NOT NULL REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    id_receptor INTEGER NOT NULL REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    texto TEXT NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'enviado',
    fecha_envio TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (id_emisor <> id_receptor)
);

CREATE TABLE grupo (
    id_grupo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    tema VARCHAR(100),
    descripcion TEXT
);

CREATE TABLE miembro_grupo (
    id_estudiante INTEGER NOT NULL REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    id_grupo INTEGER NOT NULL REFERENCES grupo(id_grupo)
        ON UPDATE CASCADE ON DELETE CASCADE,
    rol VARCHAR(30) NOT NULL DEFAULT 'miembro',
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_estudiante, id_grupo)
);

CREATE TABLE aula (
    id_aula INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bloque VARCHAR(20) NOT NULL,
    nombre VARCHAR(60) NOT NULL,
    capacidad INTEGER NOT NULL CHECK (capacidad > 0),
    UNIQUE (bloque, nombre)
);

CREATE TABLE evento (
    id_evento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_grupo INTEGER NOT NULL REFERENCES grupo(id_grupo)
        ON UPDATE CASCADE ON DELETE CASCADE,
    nombre VARCHAR(150) NOT NULL,
    fecha TIMESTAMP NOT NULL,
    lugar VARCHAR(200),
    descripcion TEXT,
    id_aula INTEGER REFERENCES aula(id_aula)
        ON UPDATE CASCADE ON DELETE SET NULL,
    detalles JSONB NOT NULL DEFAULT '{}'::jsonb,
    CHECK (jsonb_typeof(detalles) = 'object')
);

CREATE TABLE asistente_evento (
    id_estudiante INTEGER NOT NULL REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    id_evento INTEGER NOT NULL REFERENCES evento(id_evento)
        ON UPDATE CASCADE ON DELETE CASCADE,
    estado VARCHAR(20) NOT NULL DEFAULT 'inscrito',
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_estudiante, id_evento)
);

CREATE TABLE publicacion (
    id_publicacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante INTEGER NOT NULL REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    -- El contenido se representa como JSONB para admitir texto, hashtags,
    -- adjuntos, menciones y otros atributos variables.
    contenido JSONB NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo VARCHAR(30) NOT NULL DEFAULT 'texto',
    CONSTRAINT ck_publicacion_contenido_objeto
        CHECK (jsonb_typeof(contenido) = 'object' AND contenido ? 'texto')
);

CREATE TABLE comentario (
    id_comentario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_publicacion INTEGER NOT NULL REFERENCES publicacion(id_publicacion)
        ON UPDATE CASCADE ON DELETE CASCADE,
    id_estudiante INTEGER NOT NULL REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    contenido TEXT NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE reaccion (
    id_reaccion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_publicacion INTEGER NOT NULL REFERENCES publicacion(id_publicacion)
        ON UPDATE CASCADE ON DELETE CASCADE,
    id_estudiante INTEGER NOT NULL REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE CASCADE,
    tipo_reaccion VARCHAR(30) NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id_publicacion, id_estudiante)
);

-- 2. ESTRUCTURAS ADICIONALES PARA IoT Y REGISTRO DE ACTIVIDAD

CREATE TABLE dispositivo_iot (
    id_dispositivo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aula INTEGER NOT NULL REFERENCES aula(id_aula)
        ON UPDATE CASCADE ON DELETE CASCADE,
    tipo VARCHAR(30) NOT NULL
        CHECK (tipo IN ('ocupacion','ambiental','asistencia','acceso')),
    modelo VARCHAR(60),
    estado VARCHAR(15) NOT NULL DEFAULT 'activo'
        CHECK (estado IN ('activo','inactivo','falla')),
    fecha_instalacion DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE lectura_iot (
    id_lectura BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_dispositivo INTEGER NOT NULL REFERENCES dispositivo_iot(id_dispositivo)
        ON UPDATE CASCADE ON DELETE CASCADE,
    fecha_lectura TIMESTAMP NOT NULL,
    payload JSONB NOT NULL,
    PRIMARY KEY (id_lectura, fecha_lectura),
    CHECK (jsonb_typeof(payload) = 'object')
) PARTITION BY RANGE (fecha_lectura);

CREATE TABLE lectura_iot_2026_10 PARTITION OF lectura_iot
    FOR VALUES FROM ('2026-10-01') TO ('2026-11-01');
CREATE TABLE lectura_iot_2026_11 PARTITION OF lectura_iot
    FOR VALUES FROM ('2026-11-01') TO ('2026-12-01');
CREATE TABLE lectura_iot_2026_12 PARTITION OF lectura_iot
    FOR VALUES FROM ('2026-12-01') TO ('2027-01-01');
CREATE TABLE lectura_iot_otros PARTITION OF lectura_iot DEFAULT;

CREATE TABLE log_actividad (
    id_log BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_estudiante INTEGER REFERENCES estudiante(id_estudiante)
        ON UPDATE CASCADE ON DELETE SET NULL,
    accion VARCHAR(40) NOT NULL,
    fecha_log TIMESTAMP NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (id_log, fecha_log)
) PARTITION BY RANGE (fecha_log);

CREATE TABLE log_actividad_2026_10 PARTITION OF log_actividad
    FOR VALUES FROM ('2026-10-01') TO ('2026-11-01');
CREATE TABLE log_actividad_2026_11 PARTITION OF log_actividad
    FOR VALUES FROM ('2026-11-01') TO ('2026-12-01');
CREATE TABLE log_actividad_2026_12 PARTITION OF log_actividad
    FOR VALUES FROM ('2026-12-01') TO ('2027-01-01');
CREATE TABLE log_actividad_otros PARTITION OF log_actividad DEFAULT;

